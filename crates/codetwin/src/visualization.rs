//! Markdown workspace overview and linked package details.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Component, Path, PathBuf};

use anyhow::{Context, Result, bail};
use codetwin_ir::{CodeModel, PackageDependency, PackageDependencyKind, PackageId};

/// Fixed ownership marker used to recognize generated Markdown.
pub const GENERATED: &str = "<!-- Generated by CodeTwin. -->\n";

/// A rendered document with a destination relative to the output directory.
pub struct Artifact {
    /// Relative output path.
    pub path: PathBuf,
    /// Complete Markdown content.
    pub content: String,
}

/// Render a workspace overview and one detail page for every package.
pub fn render(model: &CodeModel, root: &Path, output: &Path) -> Result<Vec<Artifact>> {
    let packages: BTreeMap<_, _> = model.packages.iter().map(|p| (&p.id, p)).collect();
    let mut overview = format!(
        "{GENERATED}\n# Repository Overview\n\nRust workspace: {} packages.\n\n",
        model.packages.len()
    );
    overview.push_str("## Packages\n\n| Package | Targets | Manifest |\n| --- | --- | --- |\n");
    for package in &model.packages {
        let kinds: BTreeSet<_> = package.targets.iter().flat_map(|t| &t.kinds).collect();
        let kinds = kinds.into_iter().cloned().collect::<Vec<_>>().join(", ");
        let _ = writeln!(
            overview,
            "| [{}]({}) | {} | [{}]({}) |",
            markdown(&package.name),
            source_link(output, &output.join(detail_path(&package.id)))?,
            kinds,
            markdown(&package.manifest_path),
            source_link(output, &root.join(&package.manifest_path))?
        );
    }
    overview.push_str("\n## Declared local dependencies\n\nArrows point from a dependent package to its dependency. Optional and conditional declarations are not evaluated. This is not a runtime call graph.\n\n```mermaid\nflowchart LR\n");
    for package in &model.packages {
        let _ = writeln!(
            overview,
            "  {}[\"{}\"]",
            identifier(&package.id),
            package.name
        );
    }
    for edge in &model.package_dependencies {
        let _ = writeln!(
            overview,
            "  {} -->|{}| {}",
            identifier(&edge.from),
            qualification(edge),
            identifier(&edge.to)
        );
    }
    overview.push_str("```\n");
    let mut artifacts = vec![Artifact {
        path: "index.md".into(),
        content: overview,
    }];
    for package in &model.packages {
        let path = detail_path(&package.id);
        let destination = output.join(&path);
        let directory = destination.parent().context("artifact has no parent")?;
        let mut text = format!(
            "{GENERATED}\n# {}\n\n[Repository Overview]({})\n\nManifest: [{}]({})\n\n## Targets\n\n| Target | Kind | Source |\n| --- | --- | --- |\n",
            markdown(&package.name),
            source_link(directory, &output.join("index.md"))?,
            markdown(&package.manifest_path),
            source_link(directory, &root.join(&package.manifest_path))?
        );
        for target in &package.targets {
            let _ = writeln!(
                text,
                "| {} | {} | [{}]({}) |",
                markdown(&target.name),
                target.kinds.join(", "),
                markdown(&target.source_path),
                source_link(directory, &root.join(&target.source_path))?
            );
        }
        for (heading, incoming) in [("Local dependencies", false), ("Dependents", true)] {
            let _ = writeln!(text, "\n## {heading}\n");
            let mut count = 0;
            for edge in &model.package_dependencies {
                let (this, other) = if incoming {
                    (&edge.to, &edge.from)
                } else {
                    (&edge.from, &edge.to)
                };
                if this != &package.id {
                    continue;
                }
                let other_package = packages
                    .get(other)
                    .context("dependency references an unknown workspace package")?;
                let condition = edge
                    .target
                    .as_ref()
                    .map(|t| format!(": {}", markdown(t)))
                    .unwrap_or_default();
                let _ = writeln!(
                    text,
                    "- [{}]({}) — {}{}",
                    markdown(&other_package.name),
                    source_link(directory, &output.join(detail_path(other)))?,
                    qualification(edge),
                    condition
                );
                count += 1;
            }
            if count == 0 {
                text.push_str("None.\n");
            }
        }
        artifacts.push(Artifact {
            path,
            content: text,
        });
    }
    Ok(artifacts)
}

/// Write rendered documents into the selected output directory.
pub fn write(output: &Path, artifacts: &[Artifact]) -> Result<()> {
    for artifact in artifacts {
        let path = output.join(&artifact.path);
        for destination in path.ancestors() {
            if destination.is_symlink() {
                bail!("refusing output symlink {}", destination.display());
            }
        }
        if path.exists() {
            let text = std::fs::read_to_string(&path)
                .with_context(|| format!("cannot inspect destination {}", path.display()))?;
            if !text.starts_with(GENERATED) {
                bail!("refusing to overwrite user-owned file {}", path.display());
            }
        }
        for parent in path.parent().into_iter().flat_map(Path::ancestors) {
            if parent.exists() && !parent.is_dir() {
                bail!("output parent {} is not a directory", parent.display());
            }
        }
    }
    for artifact in artifacts {
        let path = output.join(&artifact.path);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, &artifact.content)
            .with_context(|| format!("cannot write visualization {}", path.display()))?;
    }
    Ok(())
}

fn identifier(id: &PackageId) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let encoded: String =
        id.0.bytes()
            .flat_map(|b| [HEX[usize::from(b >> 4)], HEX[usize::from(b & 15)]])
            .map(char::from)
            .collect();
    format!("p{encoded}")
}

fn detail_path(id: &PackageId) -> PathBuf {
    let identifier = identifier(id);
    let mut remaining = identifier.as_str();
    let mut path = PathBuf::from("crates");
    // Hex identifiers are ASCII; split long identities into bounded path components.
    while remaining.len() > 120 {
        path.push(&remaining[..120]);
        remaining = &remaining[120..];
    }
    path.join(format!("{remaining}.md"))
}

fn qualification(edge: &PackageDependency) -> String {
    let mut text = match edge.kind {
        PackageDependencyKind::Normal => "normal",
        PackageDependencyKind::Dev => "dev",
        PackageDependencyKind::Build => "build",
    }
    .to_string();
    if let Some(alias) = &edge.alias {
        let _ = write!(text, "; alias {alias}");
    }
    if edge.optional {
        text.push_str("; optional");
    }
    if edge.target.is_some() {
        text.push_str("; conditional");
    }
    text
}

fn markdown(text: &str) -> String {
    text.replace('\\', "\\\\")
        .replace('|', "\\|")
        .replace('[', "\\[")
        .replace(']', "\\]")
}

fn source_link(directory: &Path, target: &Path) -> Result<String> {
    let from = normalize(directory);
    let to = normalize(target);
    let from: Vec<_> = from.components().collect();
    let to: Vec<_> = to.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut parts = vec!["..".to_string(); from.len() - common];
    for component in &to[common..] {
        parts.push(
            component
                .as_os_str()
                .to_str()
                .context("source link is not UTF-8")?
                .to_string(),
        );
    }
    let mut link = String::new();
    for byte in parts.join("/").bytes() {
        if byte.is_ascii_alphanumeric() || b"/-._~".contains(&byte) {
            link.push(char::from(byte));
        } else {
            let _ = write!(link, "%{byte:02X}");
        }
    }
    Ok(link)
}

fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                out.pop();
            }
            _ => out.push(component.as_os_str()),
        }
    }
    out
}
